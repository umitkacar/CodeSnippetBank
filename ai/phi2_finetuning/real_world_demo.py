def extract_fall_features(accel_data):
    """Extract features for fall detection"""
    data = np.array(list(accel_data))
    
    # Magnitude of acceleration
    magnitude = np.sqrt(np.sum(data**2, axis=1))
    
    features = [
        np.max(magnitude),           # Peak acceleration
        np.std(magnitude),           # Variability
        np.mean(magnitude[-10:]),    # Recent average
        magnitude[-1] - magnitude[0]  # Change over window
    ]
    
    return np.array(features)

def classify_activity(accel_data):
    """Classify current activity from accelerometer"""
    data = np.array(list(accel_data))
    
    # Simple feature extraction
    features = {
        'mean_magnitude': np.mean(np.sqrt(np.sum(data**2, axis=1))),
        'std_magnitude': np.std(np.sqrt(np.sum(data**2, axis=1))),
        'dominant_freq': estimate_dominant_frequency(data)
    }
    
    # Use pattern classifier
    activity_result = activity_classifier.process(features)
    
    return activity_result['class']  # walking, running, sitting, sleeping

def estimate_dominant_frequency(data):
    """Estimate movement frequency (ultra-simple FFT)"""
    # Simplified frequency estimation for low power
    zero_crossings = np.where(np.diff(np.sign(data[:, 2])))[0]
    if len(zero_crossings) > 1:
        avg_period = np.mean(np.diff(zero_crossings))
        return 10.0 / avg_period  # 10Hz sampling rate
    return 0.0

